#!/bin/bash
# The shaders of dwm's Vulkan renderer (runtime/wine/modules/dlls/dwmcore/shaders)
# compiled to SPIR-V and written as C arrays to vk_shaders.h next to vk.c. The
# header is committed: the Wine build needs no shader compiler. Run after a
# shader changes; needs glslangValidator (Arch: glslang).
set -euo pipefail

DIR=$(cd "$(dirname "$0")/../runtime/wine/modules/dlls/dwmcore" && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
OUT="$TMP/vk_shaders.h"

{
    echo "/* Generated by tools/dwm-shaders.sh from shaders/: do not edit. */"
    echo
} > "$OUT"
cat "$DIR/shaders/common.glsl" "$DIR/shaders/quad.vert" |
    glslangValidator -V --quiet --stdin -S vert --vn shader_quad_vert -o "$TMP/quad.h"
cat "$TMP/quad.h" >> "$OUT"
for name in texture color down up acrylic shadow outline; do
    cat "$DIR/shaders/common.glsl" "$DIR/shaders/frag.glsl" "$DIR/shaders/$name.frag" |
        glslangValidator -V --quiet --stdin -S frag --vn "shader_${name}_frag" -o "$TMP/$name.h"
    cat "$TMP/$name.h" >> "$OUT"
done
# glslang writes "const uint32_t name[]": file-local here
sed -i 's/^const uint32_t /static const uint32_t /' "$OUT"
# ... with its version and "#pragma once" before each
grep -v -e '^[[:space:]]*//' -e '#pragma once' "$OUT" | tr -d '\r' > "$DIR/vk_shaders.h"
echo "$DIR/vk_shaders.h: $(grep -c '^static const uint32_t' "$DIR/vk_shaders.h") shaders"
