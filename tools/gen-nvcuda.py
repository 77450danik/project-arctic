"""Generates runtime/wine/modules/dlls/nvcuda: the CUDA driver (nvcuda.dll) for Windows programs, forwarding every
call to the host's NVIDIA driver (libcuda.so.1).

    python tools/gen-nvcuda.py <list of the cu* symbols libcuda exports>

The list comes from the host: nm -D --defined-only /usr/lib/libcuda.so.1 | awk '$2 ~ /[TW]/ {print $3}' | grep ^cu

A Windows program and the driver share one process (Wine runs it as a Linux process), so a device pointer, a
context or a host buffer the driver hands out is valid on both sides as it is. Every driver function takes integers
and pointers only and returns a CUresult, so one forwarder serves them all: the Windows side passes the first 14
argument registers/slots on as 64-bit integers, the unix side calls the driver's function with them (System V
reads the ones it declares and ignores the rest). Not forwarded, CUDA_ERROR_NOT_SUPPORTED instead:
  - the ones that call back into the program (the driver would call Windows code with the System V convention
    on a thread of its own): cuStreamAddCallback, cuLaunchHostFunc, cuLogsRegisterCallback and the like;
  - the ones that hand out the driver's own function pointers (System V entry points): cuGetProcAddress*,
    cuGetExportTable;
  - the two that take a float by value (it would travel in another register): cuTexRefSetMipmapLevelBias/Clamp.
cuOccupancyMaxPotentialBlockSize* is forwarded when its block-size callback is NULL (Blender's Cycles passes NULL).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "runtime" / "wine" / "modules" / "dlls" / "nvcuda"
NARGS = 14
names = sorted({l.strip() for l in Path(sys.argv[1]).read_text().split() if l.strip().startswith("cu")})
UNSUPPORTED = {n for n in names if n.startswith(("cuStreamAddCallback", "cuLaunchHostFunc", "cuLogsRegisterCallback",
                                                 "cuLogsUnregisterCallback", "cuGetProcAddress", "cuGetExportTable",
                                                 "cuTexRefSetMipmapLevelBias", "cuTexRefSetMipmapLevelClamp",
                                                 "cuUserObjectCreate"))}
CALLBACK_ARG3 = {n for n in names if n.startswith("cuOccupancyMaxPotentialBlockSize")}
forwarded = [n for n in names if n not in UNSUPPORTED]
OUT.mkdir(parents=True, exist_ok=True)
_write = Path.write_text
Path.write_text = lambda self, text: _write(self, text, encoding="utf-8", newline="\n")   # LF: the Wine tree's tools read these
LGPL = """ *
 * This library is free software; you can redistribute it and/or
 * modify it under the terms of the GNU Lesser General Public
 * License as published by the Free Software Foundation; either
 * version 2.1 of the License, or (at your option) any later version.
 */
"""
args_decl = ", ".join(f"UINT64 a{i}" for i in range(NARGS))
args_use = ", ".join(f"a{i}" for i in range(NARGS))

(OUT / "Makefile.in").write_text(
    "MODULE    = nvcuda.dll\nUNIXLIB   = nvcuda.so\n\nVER_FILEDESCRIPTION_STR = \"NVIDIA CUDA Driver (Arctic: the host driver)\"\n\n"
    "SOURCES = \\\n\tmain.c \\\n\tunix.c\n")

spec = [f"@ stdcall -arch=x86_64 {n}({' '.join(['int64'] * NARGS)})" for n in names]
(OUT / "nvcuda.spec").write_text("\n".join(spec) + "\n")

(OUT / "funcs.h").write_text(
    "/* generated by tools/gen-nvcuda.py from the host libcuda's exports: the forwarded driver functions */\n"
    + "/* CUFUNC_CB: forwarded only when the block-size callback (argument 3) is NULL, main.c defines it */\n"
    + "\n".join(f"CUFUNC_CB({n})" if n in CALLBACK_ARG3 else f"CUFUNC({n})" for n in forwarded) + "\n")

(OUT / "unixlib.h").write_text(f"""/*
 * nvcuda: the parameters of the forwarder
{LGPL}
#ifndef __WINE_NVCUDA_UNIXLIB_H
#define __WINE_NVCUDA_UNIXLIB_H

#include "wine/unixlib.h"

#define NVCUDA_ARGS {NARGS}

enum nvcuda_func_index
{{
#define CUFUNC(name) idx_##name,
#define CUFUNC_CB(name) idx_##name,
#include "funcs.h"
#undef CUFUNC
#undef CUFUNC_CB
    nvcuda_func_count
}};

struct forward_params
{{
    UINT32 index;               /* enum nvcuda_func_index */
    INT32  result;              /* the CUresult */
    UINT64 args[NVCUDA_ARGS];
}};

enum nvcuda_funcs
{{
    unix_init,
    unix_forward,
    unix_funcs_count
}};

#endif
""")

stubs = "\n".join(f"CUresult WINAPI {n}( {args_decl} ) {{ FIXME( \"not supported\\n\" ); return CUDA_ERROR_NOT_SUPPORTED; }}"
                  for n in sorted(UNSUPPORTED))
specials = "\n".join(f"CUresult WINAPI {n}( {args_decl} )\n{{\n    if (a3) {{ FIXME( \"a block-size callback is not supported\\n\" ); return CUDA_ERROR_NOT_SUPPORTED; }}\n"
                     f"    return forward( idx_{n}, {args_use} );\n}}" for n in sorted(CALLBACK_ARG3))
(OUT / "main.c").write_text(f"""/*
 * NVIDIA CUDA driver (nvcuda.dll): the host's driver, called as it is
 *
 * Programs that compute on an NVIDIA card load nvcuda.dll and call the CUDA
 * driver API (Blender's Cycles, video encoders, machine learning). Here every
 * call goes to the host's driver, libcuda.so.1 (unix.c): the program and the
 * driver share the process, so the contexts, modules, device pointers and
 * pinned host buffers the driver hands out are good on both sides, and the
 * kernels a program ships (cubin, PTX) are the same on Linux. Generated by
 * tools/gen-nvcuda.py from the host driver's list of functions.
{LGPL}
#include <stdarg.h>

#include "ntstatus.h"
#define WIN32_NO_STATUS
#include "windef.h"
#include "winbase.h"
#include "winternl.h"
#include "wine/debug.h"

#include "unixlib.h"

#ifdef __x86_64__

WINE_DEFAULT_DEBUG_CHANNEL(nvcuda);

typedef INT32 CUresult;
#define CUDA_ERROR_NOT_INITIALIZED 3
#define CUDA_ERROR_NOT_SUPPORTED   801

static BOOL unix_ready;

static BOOL init_unix(void)
{{
    static INIT_ONCE once = INIT_ONCE_STATIC_INIT;
    BOOL pending;

    if (InitOnceBeginInitialize( &once, 0, &pending, NULL ) && pending)
    {{
        unix_ready = !__wine_init_unix_call() && !WINE_UNIX_CALL( unix_init, NULL );
        if (!unix_ready) WARN( "no host CUDA driver (libcuda.so.1)\\n" );
        InitOnceComplete( &once, 0, NULL );
    }}
    return unix_ready;
}}

static CUresult forward( UINT32 index, {args_decl} )
{{
    struct forward_params p = {{ index, 0, {{ {args_use} }} }};

    if (!init_unix()) return CUDA_ERROR_NOT_INITIALIZED;
    if (WINE_UNIX_CALL( unix_forward, &p )) return CUDA_ERROR_NOT_INITIALIZED;
    return p.result;
}}

#define CUFUNC(name) CUresult WINAPI name( {args_decl} ) {{ return forward( idx_##name, {args_use} ); }}
#define CUFUNC_CB(name)
#include "funcs.h"
#undef CUFUNC
#undef CUFUNC_CB


/* they take a block-size callback, which would be called with the wrong convention: forwarded only without it */
{specials}

/* not forwarded (see tools/gen-nvcuda.py) */
{stubs}

BOOL WINAPI DllMain( HINSTANCE instance, DWORD reason, void *reserved )
{{
    if (reason == DLL_PROCESS_ATTACH) DisableThreadLibraryCalls( instance );
    return TRUE;
}}

#endif  /* __x86_64__ */
""")

(OUT / "unix.c").write_text(f"""/*
 * NVIDIA CUDA driver: the host's libcuda.so.1, function by function
{LGPL}
#if 0
#pragma makedep unix
#endif

#include "config.h"

#include <dlfcn.h>
#include <pthread.h>
#include <stdarg.h>

#include "ntstatus.h"
#define WIN32_NO_STATUS
#include "windef.h"
#include "winternl.h"
#include "wine/debug.h"

#include "unixlib.h"

WINE_DEFAULT_DEBUG_CHANNEL(nvcuda);

#ifdef __x86_64__

#define CUDA_ERROR_NOT_FOUND 500

typedef INT32 (*cu_fn)( {", ".join(["UINT64"] * NARGS)} );

static const char * const names[] =
{{
#define CUFUNC(name) #name,
#define CUFUNC_CB(name) #name,
#include "funcs.h"
#undef CUFUNC
#undef CUFUNC_CB
}};

static cu_fn fns[nvcuda_func_count];
static void *libcuda;
static pthread_once_t once = PTHREAD_ONCE_INIT;

static void load(void)
{{
    unsigned int i, found = 0;

    if (!(libcuda = dlopen( "libcuda.so.1", RTLD_NOW | RTLD_LOCAL )))
    {{
        WARN( "%s\\n", dlerror() );
        return;
    }}
    for (i = 0; i < nvcuda_func_count; i++)
        if ((fns[i] = (cu_fn)dlsym( libcuda, names[i] ))) found++;
    TRACE( "%u of %u driver functions\\n", found, nvcuda_func_count );
}}

static NTSTATUS init( void *args )
{{
    pthread_once( &once, load );
    return libcuda ? STATUS_SUCCESS : STATUS_DLL_NOT_FOUND;
}}

static NTSTATUS forward( void *args )
{{
    struct forward_params *p = args;
    const UINT64 *a = p->args;

    if (p->index >= nvcuda_func_count) return STATUS_INVALID_PARAMETER;
    if (!fns[p->index])
    {{
        p->result = CUDA_ERROR_NOT_FOUND;
        return STATUS_SUCCESS;
    }}
    p->result = fns[p->index]( {", ".join(f"a[{i}]" for i in range(NARGS))} );
    return STATUS_SUCCESS;
}}

#else

static NTSTATUS init( void *args ) {{ return STATUS_NOT_SUPPORTED; }}
static NTSTATUS forward( void *args ) {{ return STATUS_NOT_SUPPORTED; }}

#endif  /* __x86_64__ */

const unixlib_entry_t __wine_unix_call_funcs[] =
{{
    init,
    forward,
}};

C_ASSERT( ARRAYSIZE(__wine_unix_call_funcs) == unix_funcs_count );
""")
print(f"{len(names)} functions: {len(forwarded)} forwarded ({len(CALLBACK_ARG3)} only without a callback), {len(UNSUPPORTED)} not supported -> {OUT}")
