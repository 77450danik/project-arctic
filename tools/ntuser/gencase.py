#!/usr/bin/env python3
"""Windows' case table (l_intl.nls, the lower case part) for win32k: names of
atoms, classes and windows compare as Windows compares them, the table
wineserver loads at its start (server/unicode.c load_intl_file).

gencase.py <l_intl.nls> <kernel/drivers/win32k/casemap.c>
"""
import struct
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    data = open(src, "rb").read()
    word = lambda i: struct.unpack_from("<H", data, i * 2)[0]
    offset = word(0)               # initial offset
    offset += word(offset)         # past the upper case table
    size = word(offset) - 1        # the lower case table
    offset += 1
    table = [word(offset + i) for i in range(size)]
    lines = []
    for i in range(0, len(table), 12):
        lines.append("\t" + " ".join("0x%04x," % v for v in table[i:i + 12]))
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("""// SPDX-License-Identifier: LGPL-2.1-or-later
/*
 * Generated by tools/ntuser/gencase.py from Windows' l_intl.nls: do not edit.
 * The lower case table, three levels deep, as wineserver reads it.
 */

#include "unicode.h"

const u16 w32_casemap[%d] = {
%s
};
""" % (size, "\n".join(lines)))
    print("casemap: %d entries" % size)


if __name__ == "__main__":
    main()
