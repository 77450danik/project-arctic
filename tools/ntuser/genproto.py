#!/usr/bin/env python3
"""The Wine server protocol (server_protocol.h, generated from protocol.def) as
win32k, USER in the kernel, reads it: the same request and reply structures,
so that the handlers of USER move into the kernel as they are and win32u keeps
sending the same requests (docs/win32k.md).

genproto.py <server_protocol.h> <kernel/drivers/win32k/protocol.h>

The header is kept in the repository: the kernel is built apart from Wine. Run
it again whenever protocol.def changes (take server_protocol.h from the build
tree, after make_requests); win32k checks the protocol version ntdll and
wineserver give it (win32k_hello, win32k_callout).
"""
import re
import sys

PRELUDE = """/* SPDX-License-Identifier: LGPL-2.1-or-later */
/*
 * Generated by tools/ntuser/genproto.py from Wine's server_protocol.h: do not
 * edit. The structures of the Wine server protocol, for win32k.
 */
#ifndef WIN32K_PROTOCOL_H
#define WIN32K_PROTOCOL_H

#include <linux/types.h>

typedef __u16 WCHAR;
typedef __s64 LONG64;
#define __int64 long long
#define WINAPI
#define FIELD_OFFSET(type, field) offsetof(type, field)
#ifndef C_ASSERT
#define C_ASSERT(e) _Static_assert(e, #e)
#endif

/* from Windows' and Wine's headers the protocol uses */
#define MAXIMUM_WAIT_OBJECTS 64
#define WH_MINHOOK (-1)
#define WH_MAXHOOK 14

struct hid_input
{
    __u32 device;
    __u32 usage;
    __u32 count;
    __u32 length;
};

struct user_entry
{
    __u64 offset;   /* shared user object offset */
    __u32 tid;      /* owner thread id */
    __u32 pid;      /* owner process id */
    __u64 id;       /* shared user object id */
    union
    {
        struct
        {
            __u16 type;       /* object type (0 if free) */
            __u16 generation; /* generation counter */
        };
        LONG64 uniq;
    };
};

"""

# names the kernel has for its own: current is a macro, thread_info a structure
RENAMES = [
    (r"\bstruct thread_info\b", "struct nt_thread_info"),
    (r"\bunsigned int current;", "unsigned int current_index;"),
]


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()
    # the system and Windows headers it includes are replaced by the prelude
    text = re.sub(r"^#include <[^>]+>\s*$", "", text, flags=re.M)
    # its own include guard goes: the prelude has one
    text = re.sub(r"^#(ifndef|define) __WINE_WINE_SERVER_PROTOCOL_H\s*$", "", text, flags=re.M)
    text = re.sub(r"^#endif /\* __WINE_WINE_SERVER_PROTOCOL_H \*/\s*$", "", text, flags=re.M)
    # MAX_USER_HANDLES lives in Wine's ntuser.h, over the protocol's handle range
    text = text.replace("#define LAST_USER_HANDLE  0xffef",
                        "#define LAST_USER_HANDLE  0xffef\n"
                        "#define MAX_USER_HANDLES ((LAST_USER_HANDLE - FIRST_USER_HANDLE + 1) >> 1)")
    for pattern, new in RENAMES:
        text = re.sub(pattern, new, text)
    # inline helpers that use the C library are not needed in the kernel
    text = re.sub(r"static inline [^{;]*\{[^}]*\}\n", "", text)
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(PRELUDE + text + "\n\n#endif /* WIN32K_PROTOCOL_H */\n")
    version = re.search(r"#define SERVER_PROTOCOL_VERSION (\d+)", text)
    print("protocol version", version.group(1) if version else "?")


if __name__ == "__main__":
    main()
