#!/usr/bin/env python3
"""The constants of Windows the handlers that came from Wine's server use
(STATUS_*, WM_*, WS_*, SWP_*, ...), for win32k: taken from Wine's own headers,
object-like #defines of the prefixes below only, so that nothing of the
kernel's own is shadowed.

gendefs.py <wine include dir> <kernel/drivers/win32k/windefs.h>
"""
import os
import re
import sys

HEADERS = ["ntstatus.h", "winuser.rh", "winnt.rh", "winuser.h", "ntuser.h", "winnt.h", "winbase.h", "winerror.h", "dde.h"]
PREFIXES = (
    "STATUS_", "ERROR_", "WM_", "WS_", "WS_EX_", "SWP_", "SW_", "SWP_", "VK_", "WH_", "HC_", "QS_", "PM_",
    "SMTO_", "KF_", "KEYEVENTF_", "MOUSEEVENTF_", "RIM_", "RIDEV_", "GA_", "GW_", "GWL_", "GWLP_",
    "GCL_", "GCLP_", "CS_", "MAX_ATOM_LEN", "MAXINTATOM", "HTCLIENT", "HT", "MA_", "SC_", "CF_",
    "ISMEX_", "QS_", "MSGF_", "EVENT_", "WINEVENT_", "OBJID_", "CHILDID_", "SPI_", "DCX_", "RDW_",
    "WPF_", "MK_", "XBUTTON", "INPUT_", "LLKHF_", "LLMHF_", "HSHELL_", "SIZE_", "WVR_", "ULW_",
    "LWA_", "MDT_", "DPI_AWARENESS", "NTUSER_", "IMN_", "IME_", "MAXIMUM_WAIT_OBJECTS",
    "WAIT_", "INFINITE", "DESKTOP_", "WINSTA_", "UOI_", "TIMERV_", "USER_TIMER_", "WPF_",
    "PW_", "DWMWA_", "MONITOR_", "TOUCH", "POINTER_", "PT_", "SPIF_", "RDW_", "SMTO_", "TME_",
    "HOVER_", "GUI_", "FLASHW_", "CWP_", "MWMO_", "QS_", "SB_", "ESB_", "OBM_", "ICON_",
    "USER_DEFAULT_SCREEN_DPI", "DF_WINE", "WSF_", "SPI_", "WINE_", "MOUSE_", "LLMHF_", "GW_",
    "MOD_", "SYNCHRONIZE", "RI_", "RIDI_", "KBD", "HID_USAGE",
)

DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.+?)\s*(?:/\*.*)?$")
SIMPLE = re.compile(r"^[\w\s()|&~<>+\-*/x]+$")


# defined by protocol.h itself (genproto.py's prelude, or the protocol)
EXCLUDE = {"MAXIMUM_WAIT_OBJECTS", "WH_MINHOOK", "WH_MAXHOOK", "MAX_ATOM_LEN"}


def wanted(name):
    return name.startswith(PREFIXES) and name not in EXCLUDE


def main():
    inc, dst = sys.argv[1], sys.argv[2]
    seen, out = set(), []
    for header in HEADERS:
        path = os.path.join(inc, header)
        if not os.path.exists(path):
            continue
        for line in open(path, encoding="utf-8", errors="replace"):
            m = DEFINE.match(line)
            if not m or "(" in m.group(1):
                continue
            name, value = m.group(1), m.group(2).strip()
            if not wanted(name) or name in seen:
                continue
            value = re.sub(r"__MSABI_LONG\(([^()]*)\)", r"(\1)", value)
            value = re.sub(r"\(\s*(NTSTATUS|LONG|DWORD|ULONG|UINT|INT|WORD|BYTE|LONG_PTR|ULONG_PTR|UINT_PTR|INT_PTR)\s*\)",
                           "", value)
            value = re.sub(r"(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", value)
            if not SIMPLE.match(value) or value.startswith(("__", "WINE")):
                continue
            seen.add(name)
            out.append("#define %s %s" % (name, value))
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* SPDX-License-Identifier: LGPL-2.1-or-later */\n"
                "/* Generated by tools/ntuser/gendefs.py from Wine's headers: do not edit. */\n"
                "#ifndef WIN32K_WINDEFS_H\n#define WIN32K_WINDEFS_H\n\n")
        f.write("\n".join(out))
        f.write("\n\n#endif\n")
    print("%d constants" % len(out))


if __name__ == "__main__":
    main()
